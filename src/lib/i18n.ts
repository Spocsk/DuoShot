export function t(locale: Locale, key: keyof typeof fr): string {
  return (locale === "en" ? en : fr)[key];
}

export function tf(locale: Locale, key: keyof typeof fr, vars: Record<string, string | number>): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

