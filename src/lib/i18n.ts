export function t(locale: Locale, key: keyof typeof fr): string {
  return (locale === "en" ? en : fr)[key];
}

function pluralKey(locale: Locale, key: keyof typeof fr, n: unknown): keyof typeof fr {
  if (typeof n !== "number") return key;
  if (new Intl.PluralRules(locale).select(n) !== "one") return key;
  const one = `${key}_one`;
  return one in fr ? (one as keyof typeof fr) : key;
}

export function tf(locale: Locale, key: keyof typeof fr, vars: Record<string, string | number>): string {
  return t(locale, pluralKey(locale, key, vars.n)).replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? ""));
}

export function i18nKeys(): { fr: string[]; en: string[] } {
  return { fr: Object.keys(fr), en: Object.keys(en) };
}

